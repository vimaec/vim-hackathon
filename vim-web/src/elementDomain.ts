import * as VIM from 'vim-web'

type IElement = VIM.BIM.IElement
type ICategory = VIM.BIM.ICategory
type VimDocument = VIM.BIM.VimDocument

/**
 * Port of `CategoryDomainEnum` from vim-format
 * (src/cs/vim/Vim.Format/CategoryDomain.cs).
 *
 * The CategoryDomain is a labeling of each Revit built-in category to help
 * filter whether elements belong to more conceptual domains or whether they
 * have a physical presence in buildings.
 */
export type CategoryDomain =
  | 'Conceptual'
  | 'Physical'
  | 'Topography'
  | 'Group'
  | 'Rooms'
  | 'System'
  | 'Link'
  | 'Annotation'
  | 'Symbol'

/**
 * Port of `ElementDomainEnum` from vim-format
 * (src/cs/vim/Vim.Format/ElementDomain.cs).
 *
 * The ElementDomain is a labeling of each element which facilitates the
 * filtering of large lists of elements. The Physical and Link category
 * domains are refined per element:
 * - `PhysicalVisible` / `PhysicalHidden` — family instances in a physical
 *   category, split by whether they are visible in a 3D view.
 * - `PhysicalNotInstanced` — elements in a physical category that are not
 *   family instances (system families such as walls, floors, and roofs).
 */
export type ElementDomain =
  | 'Conceptual'
  | 'PhysicalVisible'
  | 'PhysicalHidden'
  | 'PhysicalNotInstanced'
  | 'Topography'
  | 'Group'
  | 'Rooms'
  | 'System'
  | 'LinkVisible'
  | 'LinkHidden'
  | 'Annotation'
  | 'Symbol'

/**
 * Computes the {@link ElementDomain} of every element row, keyed by element
 * index. Port of `ElementDomain.GetElementDomains` from vim-format.
 *
 * The C# version takes an `ElementKind[]` (derived from which entity table —
 * family, family type, family instance, … — references each element) and an
 * `elementIsVisibleIn3dView` array. Here the kinds are derived the same way
 * from the BIM document's tables, and visibility is supplied by the caller —
 * in the viewer, "has geometry in the scene" is the natural equivalent.
 *
 * @param doc BIM document of the loaded vim (`vim.bim`).
 * @param elements All element table rows (`doc.element.getAll()`).
 * @param categories All category table rows (`doc.category.getAll()`).
 * @param isVisibleIn3dView Whether the element at the given index is visible in a 3D view.
 */
export async function getElementDomains (
  doc: VimDocument,
  elements: IElement[],
  categories: ICategory[],
  isVisibleIn3dView: (elementIndex: number) => boolean
): Promise<Map<number, ElementDomain>> {
  // ElementKind equivalent: an element is Family / FamilyType / FamilyInstance
  // kind when the corresponding entity table references it.
  const [familyEls, familyTypeEls, familyInstanceEls] = await Promise.all([
    doc.family?.getAllElementIndex() ?? Promise.resolve(undefined),
    doc.familyType?.getAllElementIndex() ?? Promise.resolve(undefined),
    doc.familyInstance?.getAllElementIndex() ?? Promise.resolve(undefined),
  ])
  const familySet = new Set(familyEls ?? [])
  const familyTypeSet = new Set(familyTypeEls ?? [])
  const familyInstanceSet = new Set(familyInstanceEls ?? [])

  const categoryByIndex = new Map(categories.map((c) => [c.index, c]))

  const physicalDomain = (i: number): ElementDomain =>
    isVisibleIn3dView(i) ? 'PhysicalVisible' : 'PhysicalHidden'
  const linkDomain = (i: number): ElementDomain =>
    isVisibleIn3dView(i) ? 'LinkVisible' : 'LinkHidden'

  const getDomain = (e: IElement): ElementDomain => {
    // Family and FamilyType elements are relegated to the conceptual element domain.
    if (familySet.has(e.index) || familyTypeSet.has(e.index)) return 'Conceptual'
    const isFamilyInstance = familyInstanceSet.has(e.index)

    // Elements which are neither Family nor FamilyType are labeled based on
    // the category domain.
    const builtInCategory =
      e.categoryIndex !== undefined ? categoryByIndex.get(e.categoryIndex)?.builtInCategory : undefined
    const categoryDomain = builtInCategory !== undefined ? CATEGORY_DOMAIN_MAP[builtInCategory] : undefined
    if (categoryDomain === undefined) {
      // Special case: if the VIM file was sourced from IFC (or some source
      // other than Revit), it probably won't have a category domain. In this
      // case, we use family-instance-ness to determine whether the element
      // domain is actually conceptual.
      return isFamilyInstance ? physicalDomain(e.index) : 'Conceptual'
    }

    switch (categoryDomain) {
      case 'Conceptual': return 'Conceptual'
      case 'Physical':
        return isFamilyInstance ? physicalDomain(e.index) : 'PhysicalNotInstanced'
      case 'Topography': return 'Topography'
      case 'Group': return 'Group'
      case 'Rooms': return 'Rooms'
      case 'System': return 'System'
      case 'Link': return linkDomain(e.index)
      case 'Annotation': return 'Annotation'
      case 'Symbol': return 'Symbol'
    }
  }

  const result = new Map<number, ElementDomain>()
  for (const e of elements) result.set(e.index, getDomain(e))
  return result
}

